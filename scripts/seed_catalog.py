def _existing(client: SmokeClient, product: SeedProduct) -> str | None:
    """Return an already-seeded copy's id, or None.

    Idempotent as far as the API permits: matches exactly on name and brand
    among search results, the same approach and the same limits as
    `scripts/smoke/seeding.py` documents.
    """
    try:
        response = client.post_multipart(
            client.api("/products/search"),
            fields={"query": product.name, "top_k": 30},
        )
    except SmokeError:
        # A cold deployment's first search loads a model and can outlast any
        # sane timeout. "Unanswerable" must mean "not present", so we upload.
        return None
    if response.status != 200:
        return None
    try:
        payload = response.json()
    except SmokeError:
        return None
    for result in payload.get("results", []) if isinstance(payload, dict) else []:
        metadata = result.get("metadata") or {}
        if (
            metadata.get("name") == product.name
            and metadata.get("brand") == product.brand
        ):
            found = result.get("product_id")
            if isinstance(found, str):
                return found
    return None


def seed(client: SmokeClient, *, reuse: bool = True) -> tuple[int, int, list[str]]:
    """Upload the catalog. Returns `(created, reused, errors)`."""
    created = reused = 0
    errors: list[str] = []

    for index, product in enumerate(CATALOG, start=1):
        if reuse and _existing(client, product) is not None:
            reused += 1
            print(f"  [{index:2}/{len(CATALOG)}] reused   {product.name}")
            continue

        response = client.post_multipart(
            client.api("/products/upload"),
            fields={
                "name": product.name,
                "brand": product.brand,
                "category": product.category,
                "price": product.price,
                "description": product.description,
            },
            files={"file": (f"{product.key}.png", product.image)},
        )
        if response.status == 202:
            created += 1
            print(f"  [{index:2}/{len(CATALOG)}] uploaded {product.name}")
        else:
            errors.append(
                f"{product.key}: HTTP {response.status} {response.text[:120]}"
            )
            print(
                f"  [{index:2}/{len(CATALOG)}] FAILED   {product.name} (HTTP {response.status})"
            )

    return created, reused, errors


def wait_for_processing(client: SmokeClient, *, timeout: float) -> bool:
    """Block until the queue drains, so the catalog is searchable on return."""
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        response = client.get(client.api("/system/health"))
        if response.status != 200:
            return False
        depth = response.json().get("queue_depth")
        if depth == 0:
            return True
        print(f"    processing... queue depth {depth}")
        time.sleep(5)
    return False


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="seed_catalog",
        description="Seed a coherent demo catalog through the real upload API.",
    )
    parser.add_argument(
        "--base-url",
        default=os.environ.get("SMOKE_BASE_URL", "http://localhost:8000"),
        help="API origin (default: %(default)s).",
    )
    parser.add_argument(
        "--timeout", type=float, default=120.0, help="Per-request timeout."
    )
    parser.add_argument(
        "--processing-timeout",
        type=float,
        default=1800.0,
        help="Seconds to wait for the queue to drain (default: %(default)s).",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Upload everything again instead of reusing what is already indexed.",
    )
    parser.add_argument(
        "--no-wait",
        action="store_true",
        help="Return as soon as uploads are queued, without waiting for processing.",
    )
    parser.add_argument(
        "--list", action="store_true", help="Print the catalog and exit."
    )
    args = parser.parse_args(argv)

    if args.list:
        by_category: dict[str, int] = {}
        for item in CATALOG:
            by_category[item.category] = by_category.get(item.category, 0) + 1
        summary = ", ".join(
            f"{count} {name}" for name, count in sorted(by_category.items())
        )
        print(f"Demo catalog: {len(CATALOG)} products ({summary}).")
        print(CURRENCY_NOTE)
        for product in CATALOG:
            print(
                f"  {product.key:10} {product.name:34} {product.brand:10} "
                f"{product.price:>7} {product.category:12} {product.segment}"
            )
        return 0

    client = SmokeClient(base_url=args.base_url, timeout=args.timeout)
    print(f"Seeding {len(CATALOG)} products into {client.base_url}")
    print(CURRENCY_NOTE)
    print()

    created, reused, errors = seed(client, reuse=not args.force)
    print()
    print(f"  uploaded {created}, reused {reused}, failed {len(errors)}")
    for error in errors:
        print(f"    {error}")

    if created and not args.no_wait:
        print()
        print("  waiting for the pipeline to finish...")
        if not wait_for_processing(client, timeout=args.processing_timeout):
            print(
                "  timed out waiting for the queue to drain; products may still be processing"
            )
            return 1

    print()
    print("Catalog ready.")
    return 1 if errors else 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        print("\ninterrupted", file=sys.stderr)
        sys.exit(2)
