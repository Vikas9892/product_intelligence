@dataclass(frozen=True)
class SeedProduct:
    key: str
    name: str
    brand: str
    price: float
    segment: str
    description: str
    body: RGB
    sole: RGB
    accent: RGB
    variant: int = 0
    category: str = CATEGORY

    @property
    def image(self) -> bytes:
        """Draw the product.

        Silhouette follows the category, so the sparse `accessories` item is
        visually distinct from the footwear -- otherwise image similarity would
        rank it among shoes and muddy the very distinction it exists to show.
        """
        if self.category == SPARSE_CATEGORY:
            return images.backpack(self.body, strap=self.accent, variant=self.variant)
        return images.shoe(
            self.body, self.sole, accent=self.accent, variant=self.variant
        )


