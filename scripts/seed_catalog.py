#!/usr/bin/env python3
"""Seed a coherent demo catalog through the real upload API.

    python scripts/seed_catalog.py
    python scripts/seed_catalog.py --base-url https://api.example.com

Why this exists, separately from the smoke dataset
--------------------------------------------------

`scripts/smoke/dataset.py` seeds eight products spanning footwear, kitchenware,
bags and lighting, priced 24.50-134.99. That set is deliberately scattered:
each item is a *fixture* proving a specific behaviour, and the smoke suite
asserts relationships against it. It is not touched here.

But it makes a poor demonstration. A catalog of eight items across four
unrelated categories, priced 24-135, produces output that says more about the
seed data than about the system:

* pricing has one or two same-category comparables at most, so every estimate
  reports LOW confidence honestly but unimpressively;
* mixed price scales make any estimate look wrong at a glance -- a real upload
  priced 4000 against a catalog topping out at 135 cannot produce a sensible
  number;
* recommendations have nothing to rank, because there is barely a category to
  rank within.

This script seeds a catalog that resembles a real one instead: **one coherent
domain, one price scale, enough depth per segment that the intelligence
features have something to work with.**

What it seeds
-------------

Twenty-four running and training shoes across six brands and four segments,
priced on a single consistent scale (2,499-14,999). Enough that:

* every product has 5+ same-category comparables, so pricing has real evidence
  and confidence reflects agreement rather than scarcity;
* segments (road / trail / court / lifestyle) give recommendations a
  meaningful ranking problem;
* colours are spread across the palette, which is worth having now that colour
  is read from the product rather than the backdrop;
* one deliberate near-twin pair still exercises duplicate detection.

Everything is generated: the images are drawn by `scripts/smoke/images.py`, so
they are deterministic, dependency-free, and carry no licensing question.
Every product is named "Demo ..." and described as synthetic, exactly as the
smoke dataset is -- this is demonstration data and must never read as real.
"""

