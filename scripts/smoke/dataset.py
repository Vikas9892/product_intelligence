"""The deterministic demo catalog.

Eight products, each present for a stated reason. The value is not the size of
the catalog -- it is that the relationships between the products are known in
advance, so "recommendations work" becomes a checkable claim ("the near-twin
of the blue running shoe ranks above the desk lamp") instead of an impression.

Every product is clearly labelled demo data. Names begin with "Demo " and each
description says the item is synthetic and generated for verification. Nothing
here should ever be mistaken for a real catalog entry, in a UI or in a
database someone inherits.

Relationship map:

    shoe_blue_a  <-- near-identical twin -->  shoe_blue_b     (duplicates)
    shoe_blue_a  <-- same category, other brand -->  shoe_black
    shoe_*       <-- three tight prices -->                   (pricing)
    mug_red_a    <-- similar, same brand -->  mug_red_b
    backpack_blue <-- same model, other colour --> backpack_black
    lamp_yellow  <-- unlike everything else -->               (negative control)

The lamp earns its place by being the thing that must NOT rank highly. Without
a control, a recommender that returns everything scores just as well as one
that works.
"""

from __future__ import annotations

from dataclasses import dataclass

import images

#: Prefixed to every product name. Marks the data as synthetic wherever it
#: surfaces, and gives the idempotency lookup a distinctive term to search on.
DEMO_PREFIX = "Demo"

_DISCLAIMER = (
    "Synthetic demo product generated by scripts/smoke for deployment "
    "verification. Not real catalog data."
)


@dataclass(frozen=True)
class DemoProduct:
    """One catalog entry, and the image bytes that go with it."""

    key: str
    name: str
    brand: str
    category: str
    price: float
    description: str
    image: bytes
    #: Why this product is in the catalog. Surfaced in `--list` output so the
    #: dataset explains itself rather than needing this file open beside it.
    rationale: str

    @property
    def filename(self) -> str:
        return f"{self.key}.png"


def _describe(text: str) -> str:
    return f"{text} {_DISCLAIMER}"


# Colours are chosen to be far apart in RGB, so visual similarity tracks the
# relationships the catalog claims rather than accidental palette overlap.
_BLUE = (36, 82, 168)
_BLUE_DARK = (24, 58, 122)
_BLACK = (44, 46, 52)
_RED = (176, 58, 46)
_WHITE = (242, 240, 236)
_GREY = (96, 100, 108)
_YELLOW = (214, 176, 62)


def build_catalog() -> tuple[DemoProduct, ...]:
    """The catalog, built fresh each call from deterministic inputs."""
    return (
        DemoProduct(
            key="shoe_blue_a",
            name=f"{DEMO_PREFIX} Aurora Runner Blue",
            brand="Northwind",
            category="footwear",
            price=129.99,
            description=_describe(
                "Lightweight blue road running shoe with a white sole."
            ),
            image=images.shoe(_BLUE, _WHITE, accent=_WHITE, variant=0),
            rationale="Anchor product. Source for recommendations, pricing and duplicate checks.",
        ),
        DemoProduct(
            key="shoe_blue_b",
            name=f"{DEMO_PREFIX} Aurora Runner Blue Edition Two",
            brand="Northwind",
            category="footwear",
            price=134.99,
            description=_describe(
                "Second edition of the blue road running shoe, white sole."
            ),
            # variant=4 shifts the silhouette a few pixels: the same object,
            # not the same file. Duplicate detection has to do real visual
            # work rather than matching identical bytes.
            image=images.shoe(_BLUE, _WHITE, accent=_WHITE, variant=4),
            rationale="Near-identical twin of shoe_blue_a. Should be flagged as a duplicate.",
        ),
        DemoProduct(
            key="shoe_black",
            name=f"{DEMO_PREFIX} Trailblazer Trail Shoe Black",
            brand="Summit",
            category="footwear",
            price=119.99,
            description=_describe("Black trail running shoe with a grey lugged sole."),
            image=images.shoe(_BLACK, _GREY, accent=_GREY, variant=0),
            rationale=(
                "Same category, different brand and colour. Should be recommended "
                "for a shoe but must NOT be called a duplicate."
            ),
        ),
        DemoProduct(
            key="mug_red_a",
            name=f"{DEMO_PREFIX} Terracotta Ceramic Mug",
            brand="Kilnworks",
            category="kitchenware",
            price=24.50,
            description=_describe("Red glazed ceramic mug with a rounded handle."),
            image=images.mug(_RED, rim=_WHITE, variant=0),
            rationale="Different category entirely. Anchor for the second similarity cluster.",
        ),
        DemoProduct(
            key="mug_red_b",
            name=f"{DEMO_PREFIX} Terracotta Ceramic Mug Large",
            brand="Kilnworks",
            category="kitchenware",
            price=28.00,
            description=_describe(
                "Larger red glazed ceramic mug with a rounded handle."
            ),
            image=images.mug(_RED, rim=_WHITE, variant=6),
            rationale="Close relative of mug_red_a. Should rank first among its recommendations.",
        ),
        DemoProduct(
            key="backpack_blue",
            name=f"{DEMO_PREFIX} Voyager Daypack Blue",
            brand="Trailhead",
            category="bags",
            price=89.00,
            description=_describe("Blue 20-litre daypack with padded straps."),
            image=images.backpack(_BLUE_DARK, strap=_GREY, variant=0),
            rationale=(
                "Shares a colour family with the blue shoes but nothing else. "
                "Guards against recommendations driven by colour alone."
            ),
        ),
        DemoProduct(
            key="backpack_black",
            name=f"{DEMO_PREFIX} Voyager Daypack Black",
            brand="Trailhead",
            category="bags",
            price=94.00,
            description=_describe("Black 20-litre daypack with padded straps."),
            image=images.backpack(_BLACK, strap=_GREY, variant=0),
            rationale="Same model as backpack_blue in another colour. Third similarity cluster.",
        ),
        DemoProduct(
            key="lamp_yellow",
            name=f"{DEMO_PREFIX} Solstice Desk Lamp",
            brand="Lumen",
            category="lighting",
            price=45.00,
            description=_describe("Yellow domed desk lamp on a slim stem."),
            image=images.lamp(_YELLOW, base=_GREY),
            rationale=(
                "Negative control: unrelated to everything. Must rank BELOW real "
                "matches, otherwise a recommender that returns everything would pass."
            ),
        ),
    )


#: Convenience lookups used by the AI checks to express expectations by name
#: rather than by index.
CATALOG = build_catalog()
BY_KEY = {product.key: product for product in CATALOG}

#: The three footwear items, whose prices (129.99 / 134.99 / 119.99) form a
#: tight cluster -- enough comparables for a pricing estimate to be meaningful.
FOOTWEAR_KEYS = ("shoe_blue_a", "shoe_blue_b", "shoe_black")
